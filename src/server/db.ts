// Kết nối CSDL PostgreSQL, một kiểu SQL cho mọi môi trường:
//  - Neon (Vercel, hoặc bất kỳ đâu có DATABASE_URL):  driver HTTP @neondatabase/serverless
//  - PGlite (máy cá nhân, Docker, test):               Postgres chạy trong Node, lưu ở thư mục data/pgdata
//                                                       (hoặc chỉ trong RAM với ':memory:')
import fs from 'node:fs';
import path from 'node:path';

export type Row = Record<string, unknown>;
export interface Stmt {
  sql: string;
  params?: unknown[];
}

export interface DB {
  readonly kind: 'neon' | 'pglite';
  /** Chạy 1 câu lệnh, trả về các dòng. Tham số dạng $1, $2… */
  query(sql: string, params?: unknown[]): Promise<Row[]>;
  /** Chạy nhiều câu lệnh trong 1 giao dịch (Neon: 1 lượt gọi HTTP). */
  batch(stmts: Stmt[]): Promise<Row[][]>;
  close(): Promise<void>;
}

/** Các bước migration; chỉ số mảng + 1 = phiên bản schema sau khi áp dụng. Mọi câu đều chạy lặp lại an toàn. */
const MIGRATIONS: string[][] = [
  [
    `CREATE TABLE IF NOT EXISTS classes (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      created_at TEXT NOT NULL,
      session_started_at TEXT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS students (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
      mssv TEXT NOT NULL,
      full_name TEXT NOT NULL,
      class_code TEXT NOT NULL DEFAULT '',
      created_at TEXT NOT NULL,
      UNIQUE (class_id, mssv)
    )`,
    `CREATE INDEX IF NOT EXISTS idx_students_class ON students(class_id)`,
    `CREATE TABLE IF NOT EXISTS draws (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
      created_at TEXT NOT NULL,
      seed TEXT NOT NULL,
      n INTEGER NOT NULL,
      escape_prob DOUBLE PRECISION NOT NULL,
      duration_ms INTEGER NOT NULL,
      escapes INTEGER NOT NULL,
      params_json TEXT NOT NULL,
      script_json TEXT NOT NULL,
      roster_json TEXT NOT NULL
    )`,
    `CREATE INDEX IF NOT EXISTS idx_draws_class ON draws(class_id, created_at)`,
    `CREATE TABLE IF NOT EXISTS draw_results (
      draw_id INTEGER NOT NULL REFERENCES draws(id) ON DELETE CASCADE,
      position INTEGER NOT NULL,
      student_id INTEGER NOT NULL,
      PRIMARY KEY (draw_id, position)
    )`,
    `CREATE INDEX IF NOT EXISTS idx_draw_results_student ON draw_results(student_id)`,
  ],
];

export type DbConfig = { kind: 'neon'; url: string } | { kind: 'pglite'; dir: string | null };

/** DATABASE_URL (Neon) nếu có; ngược lại PGlite tại PGLITE_DIR (mặc định data/pgdata). */
export function dbConfigFromEnv(env: NodeJS.ProcessEnv = process.env): DbConfig {
  const url = env.DATABASE_URL || env.POSTGRES_URL;
  if (url) return { kind: 'neon', url };
  const dir = env.PGLITE_DIR ?? path.resolve(process.cwd(), 'data', 'pgdata');
  return { kind: 'pglite', dir: dir === ':memory:' ? null : dir };
}

async function openNeon(url: string): Promise<DB> {
  const { neon, neonConfig } = await import('@neondatabase/serverless');
  // chỉ dùng khi kiểm thử với proxy HTTP cục bộ của Neon (vd. http://localhost:4444/sql)
  if (process.env.NEON_HTTP_ENDPOINT) neonConfig.fetchEndpoint = process.env.NEON_HTTP_ENDPOINT;
  const sql = neon(url);
  return {
    kind: 'neon',
    query: async (q, params = []) => (await sql.query(q, params)) as Row[],
    batch: async (stmts) => (await sql.transaction(stmts.map((s) => sql.query(s.sql, s.params ?? [])))) as Row[][],
    close: async () => {},
  };
}

async function openPglite(dir: string | null): Promise<DB> {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir) fs.mkdirSync(dir, { recursive: true });
  const pg = dir ? new PGlite(dir) : new PGlite();
  await pg.waitReady;
  return {
    kind: 'pglite',
    query: async (q, params = []) => (await pg.query<Row>(q, params)).rows,
    batch: async (stmts) =>
      pg.transaction(async (tx) => {
        const out: Row[][] = [];
        for (const s of stmts) out.push((await tx.query<Row>(s.sql, s.params ?? [])).rows);
        return out;
      }),
    close: () => pg.close(),
  };
}

/** Mở CSDL và chạy migration. `':memory:'` = PGlite trong RAM (dùng cho test). */
export async function openDb(cfg: DbConfig | ':memory:' = dbConfigFromEnv()): Promise<DB> {
  const c: DbConfig = cfg === ':memory:' ? { kind: 'pglite', dir: null } : cfg;
  const db = c.kind === 'neon' ? await openNeon(c.url) : await openPglite(c.dir);
  await migrate(db);
  return db;
}

async function migrate(db: DB): Promise<void> {
  await db.query('CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)');
  const r = await db.query('SELECT COALESCE(MAX(version), 0) AS v FROM schema_version');
  const current = Number(r[0]?.v ?? 0);
  for (let v = current; v < MIGRATIONS.length; v++) {
    // khoá advisory: nhiều instance serverless khởi động cùng lúc không chạy migration chồng nhau
    await db.batch([
      { sql: 'SELECT pg_advisory_xact_lock(472910)' },
      ...MIGRATIONS[v].map((sql) => ({ sql })),
      {
        sql: 'INSERT INTO schema_version (version) SELECT $1::int WHERE NOT EXISTS (SELECT 1 FROM schema_version WHERE version = $1::int)',
        params: [v + 1],
      },
    ]);
  }
}
